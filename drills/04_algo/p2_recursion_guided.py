# 4. sum_digits — сумма цифр числа
#
# sum_digits(123)  → 6   (1 + 2 + 3)
# sum_digits(0)    → 0
#
# Уменьшение шагом: убираем последнюю цифру.
#   последняя цифра     = n % 10    (123 % 10 = 3)
#   число без последней = n // 10   (123 // 10 = 12)
#
# СТЕК для sum_digits(123):
#   КОПИЯ №1 (n=123): return 3 + sum_digits(12)
#       КОПИЯ №2 (n=12): return 2 + sum_digits(1)
#           КОПИЯ №3 (n=1): return 1 + sum_digits(0)
#               КОПИЯ №4 (n=0): return 0   ← БАЗА
#           КОПИЯ №3: 1 + 0 = 1
#       КОПИЯ №2: 2 + 1 = 3
#   КОПИЯ №1: 3 + 3 = 6
# ------------------------------------------------------------


def sum_digits(n):
    if n == 0:  # БАЗА: у 0 цифр нет
        return 0  # ← ПРОПУСК
    last = n % 10
    rest = n // 10
    return last + sum_digits(rest)  # ← ПРОПУСК


print("\n=== Задача 4: sum_digits ===")
print(sum_digits(123))  # 6
print(sum_digits(9999))  # 36
print(sum_digits(0))  # 0
print(sum_digits(1))  # 1


# ------------------------------------------------------------
# 5. reverse_string — перевернуть строку рекурсивно
#
# reverse_string("hello") → "olleh"
#
# Уменьшение шагом: отрезаем первый символ.
#   первый символ           = s[0]
#   всё кроме первого       = s[1:]
#
# Хитрость: чтобы строка перевернулась, на ПОДЪЁМЕ надо
# добавлять отрезанный символ В КОНЕЦ.
#   reverse("hello") = reverse("ello") + "h"
#                          ↑              ↑
#                  перевёрнутый хвост   первая буква в конец
# ------------------------------------------------------------


def reverse_string(s):
    if len(s) <= 1:  # БАЗА: 0 или 1 символ — уже "перевёрнут"
        return s  # ← ПРОПУСК
    return reverse_string(s[1:]) + s[0]  # ← ПРОПУСК


print("\n=== Задача 5: reverse_string ===")
print(reverse_string("hello"))  # "olleh"
print(reverse_string("python"))  # "nohtyp"
print(reverse_string("a"))  # "a"
print(reverse_string(""))  # ""


