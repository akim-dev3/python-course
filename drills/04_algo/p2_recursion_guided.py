# ------------------------------------------------------------
# 1. countdown — список чисел от n до 0
#
# countdown(3) → [3, 2, 1, 0]
# countdown(0) → [0]
#
# СТЕК КОПИЙ для countdown(3):
#   КОПИЯ №1 (n=3): return [3] + countdown(2)  ← ждёт
#       КОПИЯ №2 (n=2): return [2] + countdown(1)  ← ждёт
#           КОПИЯ №3 (n=1): return [1] + countdown(0)  ← ждёт
#               КОПИЯ №4 (n=0): return [0]  ← ждёт countdown(-1)
#                                            нет, тут другая база
#   На самом деле базу удобнее ставить на n < 0:
#       КОПИЯ №5 (n=-1): return []   ← БАЗА
#       КОПИЯ №4 получает [], делает [0] + [] = [0]
#       КОПИЯ №3 получает [0], делает [1] + [0] = [1,0]
#       КОПИЯ №2 получает [1,0], делает [2] + [1,0] = [2,1,0]
#       КОПИЯ №1 получает [2,1,0], делает [3] + ... = [3,2,1,0]
# ------------------------------------------------------------


def countdown(n):
    if n < 0:  # БАЗА: дошли до дна, возвращаем []
        return []
    return [n] + countdown(n - 1)  # ШАГ: текущее n + список для n-1


print("\n=== Задача 1: countdown ===")
print(countdown(5))  # [5, 4, 3, 2, 1, 0]
print(countdown(0))  # [0]
print(countdown(3))  # [3, 2, 1, 0]


# ------------------------------------------------------------
# 2. factorial — произведение чисел от 1 до n
#
# factorial(5) = 5 × 4 × 3 × 2 × 1 = 120
# factorial(0) = 1
#
# СТЕК для factorial(3):
#   КОПИЯ №1 (n=3): return 3 * factorial(2)
#       КОПИЯ №2 (n=2): return 2 * factorial(1)
#           КОПИЯ №3 (n=1): return 1   ← БАЗА (n <= 1)
#       КОПИЯ №2: return 2 * 1 = 2
#   КОПИЯ №1: return 3 * 2 = 6
# ------------------------------------------------------------


def factorial(n):
    if n <= 1:  # БАЗА: factorial(0) = factorial(1) = 1
        return 1
    return n * factorial(n - 1)  # ШАГ


print("\n=== Задача 2: factorial ===")
print(factorial(5))  # 120
print(factorial(0))  # 1
print(factorial(10))  # 3628800


# ------------------------------------------------------------
# 3. power — возведение в степень без оператора **
#
# power(2, 10) = 1024
# power(3, 0)  = 1   ← любое число в степени 0 = 1 (БАЗА)
#
# Шаг: power(base, exp) = base * power(base, exp - 1)
#
# Уменьшается ИМЕННО exp, не base. У base работы нет — он один и тот же
# во всех копиях. Уменьшаем то, что приближает к базе (exp == 0).
# ------------------------------------------------------------


def power(base, exp):
    if exp == 0:
        return 1  # ← ПРОПУСК: любое число в степени 0 = 1
    return base * power(base, exp - 1)  # ← ПРОПУСК: base * power от меньшего exp


print("\n=== Задача 3: power ===")
print(power(2, 10))  # 1024
print(power(3, 0))  # 1
print(power(5, 3))  # 125
print(power(2, 8))  # 256


