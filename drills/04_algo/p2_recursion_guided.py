# РАЗОГРЕВ 0a. Симметричное эхо — 1 2 3 3 2 1
#
# Запусти КАК ЕСТЬ. Посмотри на вывод. Объясни себе ПОЧЕМУ.
#
# В консоли должно появиться: 1, 2, 3, 3, 2, 1
#
# Разбор:
#   КОПИЯ №1 (n=1): print(1) → запускает №2 → ждёт → print(1) на подъёме
#       КОПИЯ №2 (n=2): print(2) → запускает №3 → ждёт → print(2)
#           КОПИЯ №3 (n=3): print(3) → запускает №4 → ждёт → print(3)
#               КОПИЯ №4 (n=4): 4 < 4 ЛОЖНО → ничего не делает, закрывается
#           ← №3 просыпается, печатает 3
#       ← №2 просыпается, печатает 2
#   ← №1 просыпается, печатает 1
#
# ВЫВОД: первый print — на СПУСКЕ (1,2,3),
#        второй print — на ПОДЪЁМЕ (3,2,1).
# ------------------------------------------------------------


def rec_func(n):
    if n < 4:
        print(n)  # СПУСК: выполняется ДО создания новой копии
        rec_func(n + 1)
        print(n)  # ПОДЪЁМ: выполняется ПОСЛЕ возврата из копии


print("=== Разогрев 0a: rec_func(1) ===")
rec_func(1)
# Ожидание: 1 2 3 3 2 1


