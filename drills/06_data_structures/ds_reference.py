# ============================================================
# LINKED LIST (связный список) — свой класс, без готовой структуры в Python
# ============================================================
# Node хранит значение + ссылку на следующий узел. Список — цепочка Node.
# Когда брать в реальности: редко (list в Python и так хорош), но это
# классика собеседований — проверяет понимание ссылок/указателей.

class Node:
    def __init__(self, value):
        self.value = value
        self.next = None


class LinkedList:
    def __init__(self):
        self.head = None

    def push_front(self, value):
        node = Node(value)
        node.next = self.head
        self.head = node

    def to_list(self):
        result = []
        current = self.head
        while current:
            result.append(current.value)
            current = current.next
        return result


